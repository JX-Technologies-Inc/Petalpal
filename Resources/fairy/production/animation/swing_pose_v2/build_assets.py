"""Register newly authored pose sheets; never edit the approved master.
Python compositing/extraction was explicitly authorized by the user.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import hashlib, json, shutil

ROOT=Path(__file__).resolve().parents[5]
HERE=Path(__file__).resolve().parent
RUNTIME=ROOT/'mobile/assets/garden/fairy/swing-pose-v2'
REVIEW=ROOT/'Resources/fairy/production/review/swing_pose_v2'
CELL=(512,640)

def build():
 RUNTIME.mkdir(parents=True,exist_ok=True); REVIEW.mkdir(parents=True,exist_ok=True)
 atlas=Image.new('RGBA',(2048,1920)); frames=[]
 def register(name,im,scale,root,hips,contact=None,support=None):
  # One uniform scale per authored sheet, never per body part or per frame.
  scaled=im.resize((round(im.width*scale),round(im.height*scale)),Image.Resampling.LANCZOS)
  dx=round(256-root[0]*scale);dy=round(600-root[1]*scale)
  frame=Image.new('RGBA',CELL);frame.alpha_composite(scaled,(dx,dy))
  index=len(frames);x=(index%4)*512;y=(index//4)*640
  atlas.alpha_composite(frame,(x,y));frame.save(HERE/(name+'.png'))
  transform=lambda p:[round(p[0]*scale+dx,4),round(p[1]*scale+dy,4)]
  frames.append(dict(id=name,index=index,rect=[x,y,512,640],root=[256,600],hips=transform(hips),
    contact=transform(contact) if contact else None,support=support))
 master=ROOT/'Resources/fairy/production/master/fairy_first_approved.png'
 register('idle_front_3q',Image.open(master),540/1134,(674,1178),(655,676))
 walk=Image.open(HERE/'walk_source.png')
 # Source grid: 3 x 2, original alpha retained. Registration uses shoe baseline.
 roots=[(256,632),(256,632),(256,632),(256,605),(256,605),(256,605)]
 contacts=[(353,626),(270,632),(353,626),(237,605),(354,605),(285,605)]
 labels=['near_heel','near_sole','near_toe','far_heel','far_sole','far_toe']
 for i in range(6):
  col=i%3;row=i//3
  # The generated first shoe crosses the nominal grid edge. Use inspected empty
  # gutters, not the grid line, so the complete shoe stays in its own frame.
  gutters=[(0,430),(435,815),(820,walk.width)]
  left,right=gutters[col]
  box=(left,round(row*walk.height/2),right,round((row+1)*walk.height/2))
  correction=round(col*walk.width/3)-left
  shift=lambda p:(p[0]+correction,p[1])
  register('walk_'+str(i),walk.crop(box),.9,shift(roots[i]),shift((256,365 if row==0 else 340)),shift(contacts[i]),labels[i])
 back=Image.open(HERE/'back_source.png')
 # Anatomical pivots manually registered in each equal source cell.
 back_data=[('turn_rear_3q',(300,775),(300,472)),('stand_back',(287,765),(287,474)),
  ('lower_back',(259,757),(259,523)),('sit_back',(260,754),(260,547))]
 for i,(name,root,hips) in enumerate(back_data):
  box=(round(i*back.width/4),0,round((i+1)*back.width/4),back.height)
  register(name,back.crop(box),.72,root,hips)
 atlas.save(HERE/'poses.png');shutil.copyfile(HERE/'poses.png',RUNTIME/'poses.png')
 manifest={'status':'NEW_POSE_ART_PENDING_MANUAL_REVIEW','method':'built-in image generation; uniform sheet registration',
  'authority':'../../master/fairy_first_approved.png','authority_sha256':hashlib.sha256(master.read_bytes()).hexdigest(),
  'cell':CELL,'atlas_size':atlas.size,'world_scale':.2,'walk_cycle_distance':48,'walk_sequence':[1,2,3,4],'frames':frames,
  'notes':['Dedicated authored poses, not rotations/mirrors of the front master.',
   'Foot contact coordinates are review calibration; no production Garden integration.']}
 (HERE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
 ts='// Generated by build_assets.py; candidate pose art awaits manual approval.\n'
 ts+='export const FAIRY_POSE_FRAMES='+json.dumps(frames,indent=2)+' as const;\n'
 ts+='export const FAIRY_POSE_SCALE=0.2;\nexport const FAIRY_WALK_CYCLE_DISTANCE=48;\n'
 (ROOT/'mobile/src/components/fairy/fairyPoseMetadata.ts').write_text(ts)
 # Review contact sheet retains each frame's registered canvas.
 sheet=Image.new('RGBA',atlas.size,'#e7ebe2');sheet.alpha_composite(atlas)
 d=ImageDraw.Draw(sheet)
 for f in frames:d.text((f['rect'][0]+8,f['rect'][1]+615),f['id'],fill='#253229')
 sheet.convert('RGB').save(REVIEW/'pose_contact_sheet.png')
 (REVIEW/'validation.json').write_text(json.dumps({'source_hash':manifest['authority_sha256'],'pose_count':len(frames),
  'rgba':True,'canvas':CELL,'master_modified':False,'manual_review_required':True},indent=2)+'\n')
 print('Registered',len(frames),'poses; atlas',atlas.size)

if __name__=='__main__':build()
